"""Verify a TextProof release bundle (T014 acceptance command).

Usage::

    python scripts/verify_release.py [--root DIR] [--preflight]

``--preflight`` runs only the checks that do not need ``release/`` yet
(presence of the release documents, frozen versions, the dictionary
exclusion, the lock counts, and the banned-token scan over ``scripts/``).
The full run additionally verifies every artifact under ``release/``
and ``review/``:

1. ``RELEASE_MANIFEST.json`` is valid and its versions match the code
   (``tool_version`` 0.1.0 in ``src/textproof/core/report.py``,
   package 1.0.0 in ``pyproject.toml``, spec 1.0.0 in
   ``src/textproof/api/routes.py``) and the built wheel.
2. ``source.zip`` matches the frozen source commit recorded in the
   manifest, file by file (names and SHA-256, via ``git archive``).
3. The wheel installs from the manifest data: name ``textproof``,
   version 1.0.0, package files present.
4. ``wheelhouse/`` holds exactly one wheel per locked package
   (37 packages in ``requirements.lock``), each version-pinned and each
   file hash present in the lock's hash list for that package.
5. ``SHA256SUMS.txt`` covers exactly the release files (source zip,
   wheel, wheelhouse wheels) and every entry recomputes.
6. Every hash recorded in the manifest recomputes (including
   ``SHA256SUMS.txt`` itself and the review files).
7. ``review/REVIEW_INDEX.md`` passes
   ``scripts/verify_review_pack.py`` against its anchor commit, and
   ``review/REVIEW_PACK_T014.md`` records the DOCX sync verdict.
8. The committed pytest log shows ``495 passed`` with exit 0.
9. The excluded dictionary (``assets/ocr/dictionaries/ppocrv6_dict.txt``,
   licence UNVERIFIED) appears in no archive listing, no wheel, no
   wheelhouse file list and no tracked-file list.
10. Token scan over the two new scripts: they contain none of the nine
    banned literals, anywhere including comments (checked with
    fragment-assembled tokens so the list itself never spells them).
    The wider T010 static gate (its own token list plus its import
    check, in ``tests/privacy/test_no_persistence.py``) is enforced by
    the committed full-pytest evidence (495 passed) and is not
    re-implemented here — spelling its token list in this file would
    itself trip that gate.
11. Offline smoke evidence: the committed logs under
    ``task_handoffs/T014/pkg/`` (fresh venv, ``--no-index`` install
    from ``wheelhouse/``) must show install exit 0, ``--help`` exit 0,
    the frozen version triple, and a standalone ``check`` that exits 1
    with a ``MISMATCH`` report — the installed wheel running on its
    own, with no checkout on the path. Anything else (notably exit 5,
    "validator unavailable") fails the release: the wheel would be
    installable but not runnable, which is T014 acceptance 2.
    The ``PYTHONPATH=<checkout>`` workaround run is recorded in the
    same evidence as diagnosis only; it does not satisfy this check.

Known unresolved items are listed in the manifest and printed at the
end of every run. Items marked blocking in the manifest fail the run
through the checks that cover them (currently U-01, the installed
wheel's standalone ``check``/``serve`` failure, enforced by the
offline-smoke check). Non-blocking items (currently the DOCX body
text drift, U-02, and the one unrecorded dependency licence, U-03)
are warnings: the DOCX drift is confined to wording clarifications
in ``PROJECT_BOOK.md`` and the frozen DOCX may only be regenerated by
a spec-owner decision, which T014 must not take on its own. Structure
(headings, tables, order) is verified in sync; see the review pack
for the exact numbers.

Local-only: reads local files and the local git object store, and runs
only local commands. Exit 0 = PASS, exit 1 = FAIL.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import subprocess
import sys
import tarfile
import zipfile
from pathlib import Path

DICT_REL = "assets/ocr/dictionaries/ppocrv6_dict.txt"
DICT_NAME = "ppocrv6_dict.txt"
EXPECTED_TOOL_VERSION = "0.1.0"
EXPECTED_PACKAGE_VERSION = "1.0.0"
EXPECTED_SPEC_VERSION = "1.0.0"
EXPECTED_LOCK_PACKAGES = 37
EXPECTED_LOCK_HASHES = 753
EXPECTED_PYTEST_PASSED = 495

# The token list is assembled from fragments on purpose: the literal
# strings must not appear anywhere in this file, because the same scan
# this list implements also runs over this file (T010 privacy suite).
_BANNED_TOKENS = (
    "url" + "open",
    "url" + "retrieve",
    "os.sys" + "tem",
    "shell=" + "True",
    "req" + "uests",
    "htt" + "px",
    "url" + "lib",
    "http." + "client",
    "sock" + "et",
)

_NAME_RE = re.compile(r"^([A-Za-z0-9_.\-]+)==([^\s;\\]+)\s*\\?\s*$")
_HASH_RE = re.compile(r"^\s*--hash=sha256:([0-9a-f]{64})\s*\\?\s*$")
_VERSION_RE = re.compile(r'^version\s*=\s*"([^"]+)"\s*$', re.MULTILINE)


def _run(argv: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(argv, cwd=str(cwd), text=True, capture_output=True)


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _check(results: list, name: str, ok: bool, detail: str = "") -> None:
    results.append((name, ok, detail))
    print(f"  [{'ok' if ok else 'FAIL'}] {name}" + (f" — {detail}" if detail else ""))


def _archive_files(root: Path, commit: str) -> dict[str, bytes]:
    proc = subprocess.run(
        ["git", "archive", commit], cwd=str(root), capture_output=True
    )
    if proc.returncode != 0:
        raise ValueError(f"git archive {commit} failed")
    files: dict[str, bytes] = {}
    with tarfile.open(fileobj=io.BytesIO(proc.stdout), mode="r|") as tar:
        for member in tar:
            if member.isfile():
                data = tar.extractfile(member)
                if data is not None:
                    files[member.name] = data.read()
    return files


def _parse_lock(path: Path) -> tuple[dict[str, dict], int]:
    packages: dict[str, dict] = {}
    current: str | None = None
    hash_total = 0
    for line in path.read_text(encoding="utf-8").splitlines():
        match = _NAME_RE.match(line)
        if match:
            current = match.group(1).lower()
            packages[current] = {"version": match.group(2), "hashes": set()}
            continue
        hmatch = _HASH_RE.match(line)
        if hmatch and current is not None:
            packages[current]["hashes"].add(hmatch.group(1))
            hash_total += 1
    return packages, hash_total


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _wheel_name_version(filename: str) -> tuple[str, str] | None:
    parts = filename.split("-")
    if len(parts) < 2 or not filename.endswith(".whl"):
        return None
    return _norm(parts[0]), parts[1]


def _read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _preflight_checks(root: Path, results: list) -> bool:
    ok_all = True

    for name in ("LICENSE", "README.md", "SECURITY.md", "THIRD_PARTY_NOTICES.md"):
        exists = (root / name).exists()
        _check(results, f"release document present: {name}", exists)
        ok_all = ok_all and exists

    tracked = _run(["git", "ls-files"], cwd=root)
    tracked_paths = tracked.stdout.splitlines() if tracked.returncode == 0 else []
    dict_tracked = DICT_REL in tracked_paths or any(
        p.endswith(DICT_NAME) for p in tracked_paths
    )
    _check(results, "dictionary not tracked in git", not dict_tracked)
    ok_all = ok_all and not dict_tracked

    report_src = _read_text(root / "src/textproof/core/report.py")
    m_tool = re.search(r'TOOL_VERSION:\s*Final\[str\]\s*=\s*"([^"]+)"', report_src)
    tool_ok = bool(m_tool) and m_tool.group(1) == EXPECTED_TOOL_VERSION
    _check(
        results,
        "tool_version is 0.1.0 (product version, not packaging version)",
        tool_ok,
        m_tool.group(1) if m_tool else "not found",
    )
    ok_all = ok_all and tool_ok

    pyproject = _read_text(root / "pyproject.toml")
    m_pkg = _VERSION_RE.search(pyproject)
    pkg_ok = bool(m_pkg) and m_pkg.group(1) == EXPECTED_PACKAGE_VERSION
    _check(results, "package version is 1.0.0 (pyproject.toml)", pkg_ok)
    ok_all = ok_all and pkg_ok

    routes_src = _read_text(root / "src/textproof/api/routes.py")
    m_spec = re.search(r'SPEC_VERSION:\s*Final\[str\]\s*=\s*"([^"]+)"', routes_src)
    spec_ok = bool(m_spec) and m_spec.group(1) == EXPECTED_SPEC_VERSION
    _check(results, "spec_version is 1.0.0", spec_ok)
    ok_all = ok_all and spec_ok

    lock_path = root / "requirements.lock"
    packages, hash_total = _parse_lock(lock_path)
    lock_ok = (
        len(packages) == EXPECTED_LOCK_PACKAGES
        and hash_total == EXPECTED_LOCK_HASHES
    )
    _check(
        results,
        "lock has 37 packages / 753 hashes",
        lock_ok,
        f"{len(packages)} packages, {hash_total} hashes",
    )
    ok_all = ok_all and lock_ok

    notices = _read_text(root / "THIRD_PARTY_NOTICES.md")
    dict_note = "UNVERIFIED" in notices and DICT_NAME in notices
    _check(results, "dictionary licence recorded UNVERIFIED", dict_note)
    ok_all = ok_all and dict_note

    banned_ok = True
    new_scripts = {
        root / "scripts" / "verify_release.py",
        root / "scripts" / "verify_review_pack.py",
    }
    for script in sorted(new_scripts):
        text = _read_text(script)
        for token in _BANNED_TOKENS:
            if token in text:
                _check(results, f"banned token in {script.name}: {token}", False)
                banned_ok = False
    if banned_ok:
        _check(
            results,
            "banned-token scan over new scripts (full text): no hits",
            True,
        )
    ok_all = ok_all and banned_ok

    setup = root / "scripts/setup_dictionary.py"
    _check(results, "setup_dictionary.py present", setup.is_file())
    ok_all = ok_all and setup.is_file()
    return ok_all


def _full_checks(root: Path, results: list) -> tuple[bool, dict]:
    ok_all = True
    release = root / "release"
    manifest_path = release / "RELEASE_MANIFEST.json"
    if not manifest_path.is_file():
        _check(results, "RELEASE_MANIFEST.json present", False)
        return False, {}
    try:
        manifest = json.loads(_read_text(manifest_path))
    except json.JSONDecodeError as exc:
        _check(results, "RELEASE_MANIFEST.json parses", False, str(exc))
        return False, {}
    _check(results, "RELEASE_MANIFEST.json parses", True)

    source_commit = manifest.get("source_commit", "")
    commit_ok = False
    if re.fullmatch(r"[0-9a-f]{40}", source_commit or ""):
        proc = _run(["git", "cat-file", "-t", source_commit], cwd=root)
        commit_ok = proc.returncode == 0 and proc.stdout.strip() == "commit"
    _check(results, "manifest source_commit is a real commit", commit_ok, source_commit)
    ok_all = ok_all and commit_ok

    versions_ok = (
        manifest.get("tool_version") == EXPECTED_TOOL_VERSION
        and manifest.get("package_version") == EXPECTED_PACKAGE_VERSION
        and manifest.get("spec_version") == EXPECTED_SPEC_VERSION
    )
    _check(results, "manifest versions match frozen values", versions_ok)
    ok_all = ok_all and versions_ok

    # --- source.zip vs frozen commit, file by file ---
    source_zip = release / "source.zip"
    zip_ok = False
    if commit_ok and source_zip.is_file():
        try:
            with zipfile.ZipFile(source_zip) as zf:
                names = zf.namelist()
                zip_files = {n: zf.read(n) for n in names if not n.endswith("/")}
            archived = _archive_files(root, source_commit)
            names_ok = set(zip_files) == set(archived)
            content_ok = names_ok and all(
                _sha256_bytes(zip_files[n]) == _sha256_bytes(archived[n])
                for n in zip_files
            )
            dict_hit = any(DICT_NAME in n for n in names)
            zip_ok = names_ok and content_ok and not dict_hit
            _check(
                results,
                "source.zip matches frozen commit file-by-file",
                zip_ok,
                f"{len(zip_files)} files in zip, {len(archived)} in commit"
                + ("; dictionary path present!" if dict_hit else ""),
            )
        except (zipfile.BadZipFile, OSError) as exc:
            _check(results, "source.zip readable", False, str(exc))
    else:
        _check(results, "source.zip present", False)
    ok_all = ok_all and zip_ok

    # --- wheel ---
    wheel_ok = False
    wheel_name = manifest.get("wheel", "")
    wheel_path = release / wheel_name if wheel_name else None
    if wheel_path is not None and wheel_path.is_file():
        try:
            with zipfile.ZipFile(wheel_path) as zf:
                names = zf.namelist()
                meta = [
                    n
                    for n in names
                    if n.endswith(".dist-info/METADATA")
                ]
                meta_ok = False
                meta_version = ""
                if meta:
                    text = zf.read(meta[0]).decode("utf-8", "replace")
                    fields = dict(
                        line.split(": ", 1)
                        for line in text.splitlines()
                        if ": " in line
                    )
                    meta_version = fields.get("Version", "")
                    meta_ok = (
                        fields.get("Name") == "textproof"
                        and meta_version == EXPECTED_PACKAGE_VERSION
                    )
                dict_hit = any(DICT_NAME in n for n in names)
                pkg_ok = any(n.startswith("textproof/") for n in names)
                wheel_ok = meta_ok and pkg_ok and not dict_hit
                _check(
                    results,
                    "wheel is textproof 1.0.0 with package files, no dictionary",
                    wheel_ok,
                    f"METADATA version {meta_version}",
                )
        except (zipfile.BadZipFile, OSError) as exc:
            _check(results, "wheel readable", False, str(exc))
    else:
        _check(results, "wheel present (manifest wheel field)", False)
    ok_all = ok_all and wheel_ok

    # --- wheelhouse vs lock ---
    packages, _ = _parse_lock(root / "requirements.lock")
    wheelhouse = release / "wheelhouse"
    wh_ok = False
    if wheelhouse.is_dir():
        wheels = sorted(p.name for p in wheelhouse.glob("*.whl"))
        by_pkg: dict[str, list[str]] = {}
        for w in wheels:
            parsed = _wheel_name_version(w)
            if parsed:
                by_pkg.setdefault(parsed[0], []).append(w)
        problems: list[str] = []
        for pkg, info in sorted(packages.items()):
            found = by_pkg.get(_norm(pkg), [])
            if len(found) != 1:
                problems.append(f"{pkg}: {len(found)} wheel(s)")
                continue
            parsed = _wheel_name_version(found[0])
            if parsed is None or parsed[1] != info["version"]:
                problems.append(f"{pkg}: version mismatch in {found[0]}")
                continue
            digest = _sha256_file(wheelhouse / found[0])
            if digest not in info["hashes"]:
                problems.append(f"{pkg}: wheel hash not in lock")
        extra = sorted(set(by_pkg) - {_norm(p) for p in packages})
        if extra:
            problems.append(f"extra wheel packages: {', '.join(extra)}")
        dict_hit = any(DICT_NAME in w for w in wheels)
        if dict_hit:
            problems.append("dictionary file present in wheelhouse")
        wh_ok = not problems
        _check(
            results,
            "wheelhouse matches lock (37 pinned wheels, hashes verified)",
            wh_ok,
            "; ".join(problems) if problems else f"{len(wheels)} wheels",
        )
    else:
        _check(results, "wheelhouse/ present", False)
    ok_all = ok_all and wh_ok

    # --- SHA256SUMS.txt ---
    sums_path = release / "SHA256SUMS.txt"
    sums_ok = False
    if sums_path.is_file():
        entries: dict[str, str] = {}
        bad_lines = 0
        for line in _read_text(sums_path).splitlines():
            parts = line.split(None, 1)
            if len(parts) != 2 or not re.fullmatch(r"[0-9a-f]{64}", parts[0]):
                bad_lines += 1
                continue
            entries[parts[1].strip()] = parts[0]
        expected = {"source.zip"}
        if wheel_name:
            expected.add(wheel_name)
        expected |= {f"wheelhouse/{w}" for w in sorted(
            p.name for p in wheelhouse.glob("*.whl")
        )} if wheelhouse.is_dir() else set()
        problems = []
        if set(entries) != expected:
            problems.append(
                f"covered {sorted(entries)} != expected {sorted(expected)}"
            )
        for rel, digest in entries.items():
            target = release / rel
            if not target.is_file() or _sha256_file(target) != digest:
                problems.append(f"hash mismatch: {rel}")
        if DICT_NAME in _read_text(sums_path):
            problems.append("dictionary listed in SHA256SUMS.txt")
        sums_ok = not problems and bad_lines == 0
        _check(
            results,
            "SHA256SUMS.txt covers all release files, all recompute",
            sums_ok,
            "; ".join(problems) if problems else f"{len(entries)} entries",
        )
    else:
        _check(results, "SHA256SUMS.txt present", False)
    ok_all = ok_all and sums_ok

    # --- manifest file hashes recompute ---
    manifest_files = manifest.get("files", {})
    mf_ok = True
    mf_problems: list[str] = []
    if not isinstance(manifest_files, dict) or not manifest_files:
        mf_ok = False
        mf_problems.append("manifest files map empty")
    else:
        for rel, entry in sorted(manifest_files.items()):
            target = root / rel
            if not target.is_file():
                mf_problems.append(f"missing: {rel}")
                continue
            if _sha256_file(target) != entry.get("sha256"):
                mf_problems.append(f"hash mismatch: {rel}")
            if target.stat().st_size != entry.get("size"):
                mf_problems.append(f"size mismatch: {rel}")
    mf_ok = not mf_problems
    _check(
        results,
        "manifest file hashes/sizes recompute",
        mf_ok,
        "; ".join(mf_problems) if mf_problems else f"{len(manifest_files)} entries",
    )
    ok_all = ok_all and mf_ok

    # --- review pack ---
    pack_path = root / "review" / "REVIEW_PACK_T014.md"
    index_path = root / "review" / "REVIEW_INDEX.md"
    pack_ok = pack_path.is_file() and index_path.is_file()
    _check(results, "review pack files present", pack_ok)
    ok_all = ok_all and pack_ok
    if pack_ok:
        pack_text = _read_text(pack_path)
        docx_ok = "## 5. DOCX" in pack_text and "DOCX_SYNC_VERDICT:" in pack_text
        _check(results, "review pack records the DOCX sync verdict", docx_ok)
        ok_all = ok_all and docx_ok
        proc = subprocess.run(
            [
                sys.executable,
                str(root / "scripts" / "verify_review_pack.py"),
                str(index_path),
                "--root",
                str(root),
            ],
            capture_output=True,
            text=True,
        )
        review_ok = proc.returncode == 0
        _check(
            results,
            "verify_review_pack.py passes on REVIEW_INDEX.md",
            review_ok,
            proc.stdout.strip().splitlines()[-1] if proc.stdout.strip() else "",
        )
        ok_all = ok_all and review_ok

    # --- committed test evidence ---
    log_path = root / "task_handoffs" / "T014" / "pkg" / "test_stdout.log"
    log_ok = False
    if log_path.is_file():
        log_text = _read_text(log_path)
        log_ok = f"{EXPECTED_PYTEST_PASSED} passed" in log_text
    _check(results, f"committed pytest log shows {EXPECTED_PYTEST_PASSED} passed", log_ok)
    ok_all = ok_all and log_ok
    codes_path = root / "task_handoffs" / "T014" / "pkg" / "exit_codes.txt"
    codes_ok = codes_path.is_file() and "pytest exit=0" in _read_text(codes_path)
    _check(results, "committed exit codes show pytest exit=0", codes_ok)
    ok_all = ok_all and codes_ok

    # --- offline smoke evidence (fresh venv, --no-index wheelhouse install) ---
    smoke_path = root / "task_handoffs" / "T014" / "pkg" / "offline_smoke.txt"
    smoke_ok = False
    smoke_detail = ""
    if smoke_path.is_file():
        values: dict[str, str] = {}
        for line in _read_text(smoke_path).splitlines():
            if line.startswith("#") or "=" not in line:
                continue
            key, _, val = line.partition("=")
            values[key.strip()] = val.strip()
        problems: list[str] = []
        if values.get("offline_install_exit") != "0":
            problems.append("offline install did not exit 0")
        if values.get("textproof_help_exit") != "0":
            problems.append("--help did not exit 0")
        if values.get("textproof_version_tool") != EXPECTED_TOOL_VERSION:
            problems.append("version tool mismatch")
        if values.get("textproof_version_package") != EXPECTED_PACKAGE_VERSION:
            problems.append("version package mismatch")
        if values.get("textproof_version_spec") != EXPECTED_SPEC_VERSION:
            problems.append("version spec mismatch")
        if values.get("standalone_check_exit") != "1":
            problems.append(
                "standalone check exit "
                f"{values.get('standalone_check_exit')} (want 1)"
            )
        if values.get("standalone_check_report_produced") == "NO":
            problems.append("standalone check produced no report")
        raw_logs = (
            "offline_install.log",
            "smoke_check_standalone.log",
            "smoke_version.json",
        )
        for name in raw_logs:
            if not (root / "task_handoffs" / "T014" / "pkg" / name).is_file():
                problems.append(f"missing raw log: {name}")
        smoke_ok = not problems
        smoke_detail = "; ".join(problems) if problems else (
            "install 0, help 0, versions 0.1.0/1.0.0/1.0.0, "
            "standalone check exit 1 MISMATCH"
        )
    else:
        smoke_detail = "offline_smoke.txt missing"
    _check(results, "offline smoke: installed wheel runs standalone", smoke_ok,
           smoke_detail)
    ok_all = ok_all and smoke_ok

    # --- dictionary zero-hit in tracked files ---
    tracked = _run(["git", "ls-files"], cwd=root)
    tracked_paths = tracked.stdout.splitlines() if tracked.returncode == 0 else []
    dict_tracked = DICT_REL in tracked_paths or any(
        p.endswith(DICT_NAME) for p in tracked_paths
    )
    _check(results, "dictionary absent from tracked files", not dict_tracked)
    ok_all = ok_all and not dict_tracked

    unresolved = manifest.get("known_unresolved_items", [])
    return ok_all, {"unresolved": unresolved if isinstance(unresolved, list) else []}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Verify the TextProof release bundle (T014)."
    )
    parser.add_argument("--root", type=Path, default=None,
                        help="Repository root (default: parent of scripts/).")
    parser.add_argument("--preflight", action="store_true",
                        help="Only run checks that do not need release/.")
    args = parser.parse_args(argv)

    script_dir = Path(__file__).resolve().parent
    root = args.root.resolve() if args.root else script_dir.parent
    results: list = []
    print(f"repository root: {root}")
    if args.preflight:
        print("mode: preflight")
        ok = _preflight_checks(root, results)
        print(f"VERIFY_RELEASE PREFLIGHT: {'PASS' if ok else 'FAIL'}")
        return 0 if ok else 1

    print("mode: full release verification")
    ok = _preflight_checks(root, results)
    full_ok, extra = _full_checks(root, results)
    ok = ok and full_ok
    unresolved = extra.get("unresolved", [])
    print()
    print("KNOWN UNRESOLVED ITEMS:")
    if unresolved:
        for item in unresolved:
            flag = "BLOCKING" if item.get("blocking") else "non-blocking"
            print(f"  - {item.get('id', '?')} [{flag}]: {item.get('title', '?')}")
    else:
        print("  (none)")
    print()
    failed = [name for name, passed, _ in results if not passed]
    print(f"checks: {len(results) - len(failed)}/{len(results)} passed")
    print(f"VERIFY_RELEASE: {'PASS' if ok else 'FAIL'}")
    return 0 if ok else 1


